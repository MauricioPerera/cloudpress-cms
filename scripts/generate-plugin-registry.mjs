import { readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { validatePluginPackage } from "../plugins/sdk/validator.js";

const root = process.cwd();
const pluginsDir = join(root, "plugins");
const output = join(root, "functions", "_plugins", "generated-registry.js");
const idPattern = /^[a-z0-9][a-z0-9-]{2,47}$/;

const entries = [];
const releases = [];

async function validatedEntry(folder, id, kind, releaseVersion = null) {
  const result = await validatePluginPackage(folder);
  if (!result.valid) throw new Error(`Plugin ${id}${releaseVersion ? ` (${releaseVersion})` : ""} no pasó el validador determinista: ${result.errors.join(" ")}`);
  if (releaseVersion && result.manifest.version !== releaseVersion) throw new Error(`La versión declarada de ${id} (${result.manifest.version}) no coincide con releases/${releaseVersion}.`);
  return { id, manifest: result.manifest, verification: result.verification, folder, kind, releaseVersion };
}

for (const item of await readdir(pluginsDir, { withFileTypes: true })) {
  if (!item.isDirectory() || !idPattern.test(item.name)) continue;
  const folder = join(pluginsDir, item.name);
  const current = await validatePluginPackage(folder);
  if (!current.manifest && current.errors.some((error) => error.includes("ENOENT"))) continue;
  if (!current.valid) throw new Error(`Plugin ${item.name} no pasó el validador determinista: ${current.errors.join(" ")}`);
  entries.push({ id: item.name, manifest: current.manifest, verification: current.verification, folder, kind: "current", releaseVersion: null });
  let archived = [];
  try { archived = await readdir(join(folder, "releases"), { withFileTypes: true }); }
  catch (error) { if (error?.code !== "ENOENT") throw error; }
  for (const release of archived) {
    if (!release.isDirectory()) continue;
    releases.push(await validatedEntry(join(folder, "releases", release.name), item.name, "release", release.name));
  }
}

entries.sort((a, b) => a.id.localeCompare(b.id));
releases.sort((a, b) => a.id.localeCompare(b.id) || a.releaseVersion.localeCompare(b.releaseVersion));

const moduleEntries = [...entries, ...releases];
const imports = moduleEntries.map((entry, index) => `import plugin${index} from "../../${entry.folder.slice(root.length + 1).replaceAll("\\", "/")}/plugin.js";`).join("\n");
const entryValue = (entry, index) => `{ manifest: ${JSON.stringify(entry.manifest, null, 2)}, verification: ${JSON.stringify(entry.verification, null, 2)}, hooks: plugin${index}, module: plugin${index} }`;
const values = entries.map((entry, index) => `  [${JSON.stringify(entry.id)}, ${entryValue(entry, index)}]`).join(",\n");
const releaseValues = entries.map((entry) => {
  const candidates = [entry, ...releases.filter((release) => release.id === entry.id)];
  const seen = new Map();
  for (const candidate of candidates) {
    const existing = seen.get(candidate.verification.sourceHash);
    if (existing && existing.verification.manifestHash !== candidate.verification.manifestHash) throw new Error(`El hash de código ${candidate.verification.sourceHash} de ${candidate.id} identifica manifiestos distintos; cambia el código o conserva un único manifiesto por hash.`);
    if (!existing) seen.set(candidate.verification.sourceHash, candidate);
  }
  const releaseRows = [...seen.values()].map((candidate) => {
    const index = moduleEntries.indexOf(candidate);
    return `    [${JSON.stringify(candidate.verification.sourceHash)}, ${entryValue(candidate, index)}]`;
  }).join(",\n");
  return `  [${JSON.stringify(entry.id)}, new Map([\n${releaseRows}\n  ])]`;
}).join(",\n");
const source = `// Generated by scripts/generate-plugin-registry.mjs. Do not edit manually.\n${imports}\n\nexport const generatedPluginRegistry = new Map([\n${values}\n]);\n\n// Every entry is bundled at build time. Values can be selected only by their verified source hash.\nexport const generatedPluginReleaseRegistry = new Map([\n${releaseValues}\n]);\n`;

await writeFile(output, source, "utf8");
console.log(JSON.stringify({ ok: true, output: "functions/_plugins/generated-registry.js", plugins: entries.map((entry) => entry.id), releases: releases.map((entry) => `${entry.id}@${entry.releaseVersion}`) }));
