import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const root = process.cwd();
const pluginsDir = join(root, "plugins");
const output = join(root, "functions", "_plugins", "generated-registry.js");
const idPattern = /^[a-z0-9][a-z0-9-]{2,47}$/;

const entries = [];
for (const item of await readdir(pluginsDir, { withFileTypes: true })) {
  if (!item.isDirectory() || !idPattern.test(item.name)) continue;
  const folder = join(pluginsDir, item.name);
  try {
    const manifest = JSON.parse(await readFile(join(folder, "manifest.json"), "utf8"));
    await readFile(join(folder, "plugin.js"), "utf8");
    if (manifest.id !== item.name) throw new Error("El id del manifiesto no coincide con su directorio.");
    entries.push({ id: item.name, manifest });
  } catch (error) {
    if (error?.code === "ENOENT") continue;
    throw new Error(`Plugin ${item.name}: ${error.message}`);
  }
}

entries.sort((a, b) => a.id.localeCompare(b.id));
const imports = entries.map((entry, index) => `import plugin${index} from "../../plugins/${entry.id}/plugin.js";`).join("\n");
const values = entries.map((entry, index) => `  [${JSON.stringify(entry.id)}, { manifest: ${JSON.stringify(entry.manifest, null, 2)}, hooks: plugin${index}, module: plugin${index} }]`).join(",\n");
const source = `// Generated by scripts/generate-plugin-registry.mjs. Do not edit manually.\n${imports}\n\nexport const generatedPluginRegistry = new Map([\n${values}\n]);\n`;

await writeFile(output, source, "utf8");
console.log(JSON.stringify({ ok: true, output: "functions/_plugins/generated-registry.js", plugins: entries.map((entry) => entry.id) }));
